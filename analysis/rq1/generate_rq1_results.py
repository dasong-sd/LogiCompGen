#!/usr/bin/env python3
"""Generate the journal RQ1 result bundle from existing experiment artifacts.

This script compares:
1. API-call traces generated by LOGICOMPGEN; and
2. API-call traces extracted from the 40 direct GPT-5-Mini test-generation
   outputs in results/rq1_sources/direct_generation.

Instruction-conditioned model executions in results/raw_evaluations are
intentionally excluded from this analysis.
"""

from __future__ import annotations

import csv
import hashlib
import json
import random
import re
import statistics
from pathlib import Path
from typing import Any, Iterable, Sequence


REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = REPO_ROOT / "results/derived/rq1"
RANDOM_SEED = 20260729
RESAMPLE_COUNT = 10_000
TRACE_BUDGET = 40
K_VALUES = (2, 3, 4)

DOMAIN_CONFIGS = {
    "financial": {
        "display_name": "Financial Services",
        "ground_truth": "data/ground_truth/bank_manager_ground_truth_cases.json",
        "benchmark": "data/benchmark/labeled_bank_manager_dataset.json",
        "gpt_baseline": "results/rq1_sources/direct_generation/BankManager_llm_baseline_raw.json",
        "api_doc": "data/api_docs/ToolEmu/BankManager/doc.json",
    },
    "tele_healthcare": {
        "display_name": "Tele-Healthcare",
        "ground_truth": "data/ground_truth/teladoc_ground_truth_cases.json",
        "benchmark": "data/benchmark/labeled_teladoc_dataset.json",
        "gpt_baseline": "results/rq1_sources/direct_generation/Teladoc_llm_baseline_raw.json",
        "api_doc": "data/api_docs/ToolEmu/Teladoc/doc.json",
    },
    "smart_home": {
        "display_name": "Smart Home IoT",
        "ground_truth": "data/ground_truth/smart_lock_ground_truth_cases.json",
        "benchmark": "data/benchmark/labeled_smart_lock_dataset.json",
        "gpt_baseline": "results/rq1_sources/direct_generation/AugustSmartLock_llm_baseline_raw.json",
        "api_doc": "data/api_docs/ToolEmu/AugustSmartLock/doc.json",
    },
}


def read_json(relative_path: str) -> Any:
    with (REPO_ROOT / relative_path).open("r", encoding="utf-8") as handle:
        return json.load(handle)


def sha256(relative_path: str) -> str:
    digest = hashlib.sha256()
    with (REPO_ROOT / relative_path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def extract_trace(code: str, api_names: set[str]) -> list[str]:
    """Use the same broad endpoint extraction rule as the original RQ1 code."""
    methods = re.findall(r"\b\w+\.(\w+)\s*\(", code or "")
    return [method for method in methods if method in api_names]


def kgrams(traces: Iterable[Sequence[str]], k: int) -> set[tuple[str, ...]]:
    return {
        tuple(trace[index : index + k])
        for trace in traces
        for index in range(len(trace) - k + 1)
    }


def kgram_opportunities(traces: Iterable[Sequence[str]], k: int) -> int:
    return sum(max(0, len(trace) - k + 1) for trace in traces)


def quantile(values: Sequence[float], probability: float) -> float:
    ordered = sorted(values)
    position = (len(ordered) - 1) * probability
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    fraction = position - lower
    return ordered[lower] + (ordered[upper] - ordered[lower]) * fraction


def summarize_traces(
    traces: list[list[str]],
    api_count: int,
    method: str,
    scope: str,
) -> dict[str, Any]:
    lengths = [len(trace) for trace in traces]
    summary: dict[str, Any] = {
        "method": method,
        "scope": scope,
        "trace_count": len(traces),
        "empty_trace_count": sum(not trace for trace in traces),
        "unique_full_trace_count": len({tuple(trace) for trace in traces}),
        "minimum_trace_length": min(lengths),
        "mean_trace_length": statistics.mean(lengths),
        "median_trace_length": statistics.median(lengths),
        "maximum_trace_length": max(lengths),
    }
    for k in K_VALUES:
        unique_count = len(kgrams(traces, k))
        opportunities = kgram_opportunities(traces, k)
        summary[f"unique_{k}gram_count"] = unique_count
        summary[f"{k}gram_opportunity_count"] = opportunities
        summary[f"{k}gram_novelty_ratio"] = unique_count / opportunities if opportunities else 0.0
    summary["atc"] = summary["unique_2gram_count"] / (api_count**2)
    return summary


def repeated_subsampling(
    logicompgen_traces: list[list[str]],
    gpt_traces: list[list[str]],
    api_count: int,
    seed: int,
) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    sampled_metrics: dict[str, list[float]] = {
        "atc": [],
        "unique_2gram_count": [],
        "unique_3gram_count": [],
        "unique_4gram_count": [],
    }
    for _ in range(RESAMPLE_COUNT):
        sample = rng.sample(logicompgen_traces, TRACE_BUDGET)
        unique_counts = {k: len(kgrams(sample, k)) for k in K_VALUES}
        sampled_metrics["atc"].append(unique_counts[2] / (api_count**2))
        for k in K_VALUES:
            sampled_metrics[f"unique_{k}gram_count"].append(float(unique_counts[k]))

    gpt_values = {
        "atc": len(kgrams(gpt_traces, 2)) / (api_count**2),
        **{f"unique_{k}gram_count": float(len(kgrams(gpt_traces, k))) for k in K_VALUES},
    }

    rows = []
    for metric, values in sampled_metrics.items():
        baseline = gpt_values[metric]
        rows.append(
            {
                "metric": metric,
                "logicompgen_mean": statistics.mean(values),
                "logicompgen_median": statistics.median(values),
                "logicompgen_ci95_lower": quantile(values, 0.025),
                "logicompgen_ci95_upper": quantile(values, 0.975),
                "gpt5_mini_value": baseline,
                "proportion_logicompgen_greater": sum(value > baseline for value in values)
                / len(values),
                "proportion_logicompgen_greater_or_equal": sum(value >= baseline for value in values)
                / len(values),
            }
        )
    return rows


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        return
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    result: dict[str, Any] = {
        "rq": "RQ1",
        "objective": (
            "Compare structural API-call trace coverage between LOGICOMPGEN "
            "and direct GPT-5-Mini test generation."
        ),
        "comparison_scope": {
            "primary_budget": f"{TRACE_BUDGET} generated traces per method and domain",
            "logicompgen_population": "All 300 existing generated traces per domain",
            "logicompgen_resampling": (
                f"{RESAMPLE_COUNT} random samples of {TRACE_BUDGET} traces without replacement"
            ),
            "gpt5_mini_population": (
                f"The {TRACE_BUDGET} direct test-generation outputs in "
                "results/rq1_sources/direct_generation for each domain"
            ),
            "excluded_data": (
                "Instruction-conditioned GPT-5-Mini executions under "
                "results/raw_evaluations"
            ),
            "cost_boundary": (
                "The experiment compares structural coverage per generated trace. "
                "It does not compare token, monetary, or wall-clock cost."
            ),
        },
        "definitions": {
            "atc": "number of unique adjacent API pairs divided by |API vocabulary|^2",
            "k_trace": "number of unique contiguous API subsequences of length k",
            "kgram_novelty_ratio": (
                "number of unique k-grams divided by the total observable k-gram positions"
            ),
        },
        "random_seed": RANDOM_SEED,
        "resample_count": RESAMPLE_COUNT,
        "trace_budget": TRACE_BUDGET,
        "domains": {},
    }

    summary_rows: list[dict[str, Any]] = []
    resampling_rows: list[dict[str, Any]] = []
    source_rows: list[dict[str, Any]] = []

    for domain_key, config in DOMAIN_CONFIGS.items():
        api_doc = read_json(config["api_doc"])
        api_names = {tool["name"] for tool in api_doc["tools"]}

        ground_truth = read_json(config["ground_truth"])["test_cases"]
        all_logicompgen_traces = [
            extract_trace(case.get("generated_program", ""), api_names) for case in ground_truth
        ]
        all_logicompgen_traces = [trace for trace in all_logicompgen_traces if trace]

        case_by_id = {case["trace_id"]: case for case in ground_truth}
        benchmark_items = read_json(config["benchmark"])
        selected_ids = [item["trace_id"] for item in benchmark_items if item.get("trace_id")]
        selected_logicompgen_traces = [
            extract_trace(case_by_id[trace_id].get("generated_program", ""), api_names)
            for trace_id in selected_ids
        ]

        gpt_items = read_json(config["gpt_baseline"])
        gpt_traces = [list(item.get("extracted_trace", [])) for item in gpt_items]

        if len(all_logicompgen_traces) != 300:
            raise ValueError(
                f"{domain_key}: expected 300 LOGICOMPGEN traces, got "
                f"{len(all_logicompgen_traces)}"
            )
        if len(selected_logicompgen_traces) != TRACE_BUDGET:
            raise ValueError(
                f"{domain_key}: expected {TRACE_BUDGET} selected traces, got "
                f"{len(selected_logicompgen_traces)}"
            )
        if len(gpt_traces) != TRACE_BUDGET:
            raise ValueError(
                f"{domain_key}: expected {TRACE_BUDGET} GPT traces, got {len(gpt_traces)}"
            )

        selected_summary = summarize_traces(
            selected_logicompgen_traces,
            len(api_names),
            method="logicompgen",
            scope="benchmark_selected_40",
        )
        gpt_summary = summarize_traces(
            gpt_traces,
            len(api_names),
            method="gpt5_mini",
            scope="direct_generation_40",
        )
        resampling = repeated_subsampling(
            all_logicompgen_traces,
            gpt_traces,
            len(api_names),
            seed=RANDOM_SEED,
        )

        for summary in (selected_summary, gpt_summary):
            summary_rows.append(
                {
                    "domain": domain_key,
                    "display_name": config["display_name"],
                    "api_count": len(api_names),
                    **summary,
                }
            )
        for row in resampling:
            resampling_rows.append(
                {
                    "domain": domain_key,
                    "display_name": config["display_name"],
                    **row,
                }
            )
        for source_name in ("ground_truth", "benchmark", "gpt_baseline", "api_doc"):
            relative_path = config[source_name]
            source_rows.append(
                {
                    "domain": domain_key,
                    "source_type": source_name,
                    "path": relative_path,
                    "sha256": sha256(relative_path),
                }
            )

        result["domains"][domain_key] = {
            "display_name": config["display_name"],
            "api_count": len(api_names),
            "logicompgen_all_trace_count": len(all_logicompgen_traces),
            "logicompgen_selected": selected_summary,
            "gpt5_mini_direct": gpt_summary,
            "logicompgen_repeated_subsampling": resampling,
        }

    with (OUTPUT_DIR / "rq1_results.json").open("w", encoding="utf-8") as handle:
        json.dump(result, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    write_csv(OUTPUT_DIR / "rq1_summary.csv", summary_rows)
    write_csv(OUTPUT_DIR / "rq1_resampling_summary.csv", resampling_rows)
    write_csv(OUTPUT_DIR / "source_manifest.csv", source_rows)


if __name__ == "__main__":
    main()
